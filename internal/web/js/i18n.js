// t は英語の文 s を今の言語にする。{name} は vars の値で埋める（日本語では語順が変わるので、文ごと鍵にする）
function t(s, vars){
  let r = isJA() && Object.prototype.hasOwnProperty.call(JA_TEXT, s) ? JA_TEXT[s] : s;
  if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m);
  return r;
}
/* テンプレート（template.html）に書いてある文言を、今の言語にする。data-t のある要素の文字と、
   title・aria-label・placeholder を辞書で引く。動きで描く部分（履歴が入る）は対象にしない */
function applyStaticText(){
  if (!JA) return;
  document.documentElement.lang = "ja";
  document.querySelectorAll("[data-t]").forEach(el => {
    for (const n of el.childNodes) if (n.nodeType === 3 && n.textContent.trim()) n.textContent = n.textContent.replace(n.textContent.trim(), t(n.textContent.trim()));
    for (const a of ["title", "aria-label", "placeholder"]) if (el.hasAttribute(a)) el.setAttribute(a, t(el.getAttribute(a)));
  });
}
// setLang は言語を切り替えて開き直す（?lang= を付ける。ほかの検索パラメーターと # はそのまま）
function setLang(l){
  store.set("lang", l);
  // 開き直しても、見ていた期間と開いていたセッションをそのままにする（このタブの中だけ）
  try { sessionStorage.setItem("kiroku:keep", JSON.stringify({week: key(st.week), month: mkey(st.month), mode: st.mode, sel: st.sel})); } catch(e){}
  const u = new URL(location.href); u.searchParams.set("lang", l); location.replace(u.href);
}
